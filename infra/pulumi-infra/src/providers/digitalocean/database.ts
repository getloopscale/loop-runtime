import * as digitalocean from "@pulumi/digitalocean";
import { IProviderDatabase } from "../../contracts/provider";
import { DatabaseClusterSpec, DatabaseClusterOutput } from "../../contracts/database";
import { resolveDbSize } from "./nodes";
import { tagsToStringArray } from "../../core/tags";

/**
 * DigitalOcean managed database provider.
 *
 * Creates a managed PostgreSQL cluster inside the VPC.
 * Platform state (jobs, installs, metadata) lives here — not in K8s.
 *
 * DigitalOcean managed databases provide:
 * - Automatic daily backups (7-day retention)
 * - Automatic failover (HA plans)
 * - Automatic maintenance windows
 * - Private networking via VPC
 */
export class DigitalOceanDatabaseProvider implements IProviderDatabase {
  createDatabaseCluster(spec: DatabaseClusterSpec): DatabaseClusterOutput {
    const cluster = new digitalocean.DatabaseCluster(spec.name, {
      name: spec.name,
      engine: "pg",
      version: spec.version,
      size: resolveDbSize(spec.size),
      region: spec.region,
      nodeCount: spec.nodeCount,
      privateNetworkUuid: spec.network.vpcId,
      tags: tagsToStringArray(spec.tags),
    });

    // Managed PostgreSQL only creates "defaultdb". Platform services need their own databases.
    new digitalocean.DatabaseDb(`${spec.name}-gitea`, {
      clusterId: cluster.id,
      name: "gitea",
    });

    new digitalocean.DatabaseDb(`${spec.name}-loop-runtime`, {
      clusterId: cluster.id,
      name: "loop-runtime",
    });

    // Ory Kratos (identity management) and Hydra (OAuth2 server) require separate databases.
    // Each manages its own migration history and expects full ownership of the database.
    new digitalocean.DatabaseDb(`${spec.name}-kratos`, {
      clusterId: cluster.id,
      name: "kratos",
    });

    new digitalocean.DatabaseDb(`${spec.name}-hydra`, {
      clusterId: cluster.id,
      name: "hydra",
    });

    // Firewall: allow only specified K8s clusters to connect.
    // Without this, the DB is unreachable from all pods (connection timeout on port 25060).
    // This is critical for idempotency — destroy+recreate must re-add firewall rules.
    if (spec.trustedK8sClusters && spec.trustedK8sClusters.length > 0) {
      new digitalocean.DatabaseFirewall(`${spec.name}-firewall`, {
        clusterId: cluster.id,
        rules: spec.trustedK8sClusters.map((id, i) => ({
          type: "k8s",
          value: id,
        })),
      });
    }

    // PostgreSQL config tuning — enables pg_stat_statements, sets safe timeouts.
    // These settings are applied at the cluster level, not per-database.
    new digitalocean.DatabasePostgresqlConfig(`${spec.name}-pgconfig`, {
      clusterId: cluster.id,
      // pg_stat_statements: track all queries for slow query analysis
      pgStatStatementsTrack: "all",
      // Log queries slower than 1 second
      logMinDurationStatement: 1000,
      // Kill idle transactions after 10 minutes (prevents connection leaks)
      idleInTransactionSessionTimeout: 600000,
      // Shared buffers at 25% of RAM (DO default, explicit for clarity)
      sharedBuffersPercentage: 25,
      // Work memory per query operation (4MB, good for sorting/hashing)
      workMem: 4,
    });

    // Separate database users per service — avoids shared credentials.
    // DO DatabaseUser passwords are auto-generated by the provider and
    // exposed via the .password output (encrypted in Pulumi state).
    const apiUser = new digitalocean.DatabaseUser(`${spec.name}-api-user`, {
      clusterId: cluster.id,
      name: "loop_runtime_api",
    });

    // Gitea user — Helm chart needs a user that can create tables in the gitea DB.
    // Without this, Gitea init-container crashes with "password authentication failed".
    const giteaUser = new digitalocean.DatabaseUser(`${spec.name}-gitea-user`, {
      clusterId: cluster.id,
      name: "gitea",
    });

    // Kratos user (identity management)
    const kratosUser = new digitalocean.DatabaseUser(`${spec.name}-kratos-user`, {
      clusterId: cluster.id,
      name: "kratos",
    });

    // Hydra user (OAuth2 server)
    const hydraUser = new digitalocean.DatabaseUser(`${spec.name}-hydra-user`, {
      clusterId: cluster.id,
      name: "hydra",
    });

    // PGBouncer connection pool — managed by DO, not the application.
    // Eliminates the need for pgx pool tuning in the API (DB_MAX_CONNS).
    // Transaction mode: connections returned to pool after each transaction.
    // Size 20: enough for 2 API replicas × 10 concurrent requests.
    new digitalocean.DatabaseConnectionPool(`${spec.name}-api-pool`, {
      clusterId: cluster.id,
      name: "loop-runtime-api-pool",
      mode: "transaction",
      size: 20,
      dbName: "loop_runtime",
      user: apiUser.name,
    });

    return {
      clusterId: cluster.id,
      host: cluster.host,
      privateHost: cluster.privateHost,
      port: cluster.port,
      database: cluster.database,
      user: cluster.user,
      password: cluster.password,
      uri: cluster.uri,
      // Additional outputs for downstream consumers
      apiUser: apiUser.name,
      apiUserPassword: apiUser.password,
      giteaUser: giteaUser.name,
      giteaUserPassword: giteaUser.password,
      kratosUser: kratosUser.name,
      kratosUserPassword: kratosUser.password,
      hydraUser: hydraUser.name,
      hydraUserPassword: hydraUser.password,
    };
  }
}
