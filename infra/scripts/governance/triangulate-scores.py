#!/usr/bin/env python3
"""
triangulate-scores.py — Compute convergence metrics from 3 persona score YAML outputs.

Per T3.2 of status-validation-and-doc-consolidation-plan.

Input: 3 yaml files (p1/p2/p3) per schema in docs/governance/personas/README.md
Output: triangulation.yaml with median + std-dev + flag per dimension

Usage:
  scripts/triangulate-scores.py p1.yaml p2.yaml p3.yaml > triangulation.yaml

Exit codes:
  0 — all dimensions converge (std-dev <= 0.3 per dim)
  1 — one or more dimensions flagged (std-dev > 0.3) — reconciliation meeting required
"""

import sys
import json
import statistics
from pathlib import Path

# Minimal YAML loader (avoid pyyaml dep)
def load_yaml(path):
    with open(path, 'r') as f:
        content = f.read()
    result = {}
    current_section = None
    current_dim = None
    for line in content.split('\n'):
        if not line.strip() or line.startswith('#'):
            continue
        if line.startswith('  ') and ':' in line:
            stripped = line.strip()
            if stripped.endswith(':') and not stripped.startswith('-'):
                # nested key
                if current_section == 'scores':
                    current_dim = stripped[:-1]
                    result.setdefault('scores', {})[current_dim] = {}
            elif ':' in stripped and current_dim and current_section == 'scores':
                k, v = stripped.split(':', 1)
                v = v.strip()
                if v:
                    if v.replace('.', '').isdigit():
                        result['scores'][current_dim][k.strip()] = float(v)
                    else:
                        result['scores'][current_dim][k.strip()] = v
        elif ':' in line and not line.startswith(' '):
            k, v = line.split(':', 1)
            v = v.strip()
            if v:
                result[k.strip()] = v
            else:
                current_section = k.strip()
                if current_section == 'scores':
                    result['scores'] = {}
    return result

def triangulate(p1, p2, p3):
    """Compute median + std-dev for each dimension. Flag if std-dev > 0.3."""
    dimensions = ['core_deploy_flow', 'dx_cli', 'infra_ops', 'security',
                  'scale_multitenancy', 'product_completeness', 'tests_confidence']

    triangulated = {
        'computed_at': str(__import__('datetime').date.today()),
        'personas': {
            'p1': p1.get('persona', 'p1'),
            'p2': p2.get('persona', 'p2'),
            'p3': p3.get('persona', 'p3'),
        },
        'models': {
            'p1': p1.get('model', 'unknown'),
            'p2': p2.get('model', 'unknown'),
            'p3': p3.get('model', 'unknown'),
        },
        'dimensions': {},
        'flags': [],
    }

    for dim in dimensions:
        scores = []
        for p in (p1, p2, p3):
            s = p.get('scores', {}).get(dim, {}).get('score')
            if s is None:
                print(f"WARN: persona {p.get('persona')} missing dim {dim}", file=sys.stderr)
                continue
            scores.append(float(s))

        if len(scores) < 3:
            triangulated['dimensions'][dim] = {
                'error': 'incomplete_data',
                'scores_provided': len(scores),
            }
            triangulated['flags'].append({
                'dimension': dim,
                'reason': 'incomplete_data',
            })
            continue

        median = statistics.median(scores)
        stdev = statistics.stdev(scores)
        flagged = stdev > 0.3

        triangulated['dimensions'][dim] = {
            'p1_score': scores[0],
            'p2_score': scores[1],
            'p3_score': scores[2],
            'median': round(median, 2),
            'std_dev': round(stdev, 3),
            'flagged': flagged,
            'final_score': round(median, 2) if not flagged else None,  # null until reconciled
        }

        if flagged:
            triangulated['flags'].append({
                'dimension': dim,
                'std_dev': round(stdev, 3),
                'reason': 'std_dev > 0.3 — reconciliation meeting required (T3.3)',
            })

    return triangulated

def main():
    if len(sys.argv) != 4:
        print("Usage: triangulate-scores.py <p1.yaml> <p2.yaml> <p3.yaml>", file=sys.stderr)
        sys.exit(1)

    p1 = load_yaml(sys.argv[1])
    p2 = load_yaml(sys.argv[2])
    p3 = load_yaml(sys.argv[3])

    result = triangulate(p1, p2, p3)

    # Output as YAML (manual emit, no pyyaml dep)
    print("# Triangulation result — generated by scripts/triangulate-scores.py")
    print(f"computed_at: {result['computed_at']}")
    print("personas:")
    for k, v in result['personas'].items():
        print(f"  {k}: {v}")
    print("models:")
    for k, v in result['models'].items():
        print(f"  {k}: {v}")
    print("dimensions:")
    for dim, data in result['dimensions'].items():
        print(f"  {dim}:")
        for k, v in data.items():
            if isinstance(v, bool):
                v = 'true' if v else 'false'
            elif v is None:
                v = 'null'
            print(f"    {k}: {v}")
    print(f"flags_count: {len(result['flags'])}")
    if result['flags']:
        print("flagged_dimensions:")
        for f in result['flags']:
            print(f"  - {f['dimension']} (reason: {f['reason']})")

    sys.exit(0 if not result['flags'] else 1)

if __name__ == '__main__':
    main()
