# Plan 2026-05-16-drill-l2-unlock T4.7.bis (EC-03 MUST FIX).
#
# Fault-tolerant drill evidence capture with commit-before-teardown.
#
# Why this exists
# ---------------
# Drill stack destruction is IRREVERSIBLE. ~90min of harness work + $0.85
# cost lost if evidence capture fails silently. Plan T4.7 (D5) assumes
# happy-path evidence capture (kubectl exec mid-collection succeeds,
# audit doc write succeeds, commit succeeds). EC-03: any single failure
# during evidence collection MUST NOT result in zero-evidence runs.
#
# This script wraps evidence collection with:
#   - `set +e` around each kubectl/curl/pulumi call (no early exit)
#   - Per-step output written to /tmp/drill-evidence-${run_id}/ (each step
#     a separate file so partial state is recoverable)
#   - Audit-doc skeleton always written FIRST (before any data collection)
#   - Local git commit before final teardown (operator can git stash apply
#     to recover if /tmp wiped)
#   - Idempotent: re-run overwrites partial fragments but preserves git log
#
# Per ADR D5: evidence persists BEFORE pulumi destroy. Without persistent
# evidence, drill runs don't accumulate maturity claims per Rule 11
# (3 evidence sources requirement).
#
# Usage:
#   bash infra/scripts/drill/evidence-capture.sh <run_id> [--dry-run]
#
# Example:
#   bash infra/scripts/drill/evidence-capture.sh "drill-l2-2026-05-17-1430"
#
# Exit codes:
#   0 — Evidence captured + committed (even if some fragments missing)
#   1 — Tool missing OR run_id not provided
#   2 — Audit dir not writable
#   3 — Git operations failed (operator must investigate state)
#   4 — Argument error
#
# Environment:
#   DRILL_KUBECONFIG_DIR — default /tmp/drill-kc (for kubectl exec capture)
#   PULUMI_DRILL_DIR — default infra/pulumi-drill
#   EVIDENCE_DIR — default /tmp/drill-evidence-${run_id}
#   AUDIT_DOC_DIR — default .claude/knowledge-base/audits

set -euo pipefail

# --- Argument parsing ---
DRY_RUN=false
RUN_ID=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run) DRY_RUN=true; shift ;;
    -h|--help)
      cat <<'HELP'
evidence-capture.sh — Fault-tolerant drill evidence capture

  <run_id>      Required: unique identifier for this drill run
                Format: drill-{level}-{date}-{tag} (e.g., drill-l2-2026-05-17-1430)
  --dry-run     Preview steps without actual capture
  -h, --help    Show this help

Plan: 2026-05-16-drill-l2-unlock T4.7.bis (EC-03 MUST FIX)
HELP
      exit 0 ;;
    -*)
      echo "[drill-evidence-capture] ERROR: unknown flag $1" >&2
      exit 4 ;;
    *)
      if [[ -z "$RUN_ID" ]]; then
        RUN_ID="$1"
      else
        echo "[drill-evidence-capture] ERROR: too many positional args" >&2
        exit 4
      fi
      shift ;;
  esac
done

if [[ -z "$RUN_ID" ]]; then
  echo "[drill-evidence-capture] ERROR: run_id positional arg required (e.g., drill-l2-2026-05-17-1430)" >&2
  exit 1
fi

# Sanitize RUN_ID (filesystem + git branch safe)
if ! [[ "$RUN_ID" =~ ^[a-zA-Z0-9._-]+$ ]]; then
  echo "[drill-evidence-capture] ERROR: run_id contains invalid chars (allow [a-zA-Z0-9._-])" >&2
  exit 4
fi

DRILL_KUBECONFIG_DIR="${DRILL_KUBECONFIG_DIR:-/tmp/drill-kc}"
PULUMI_DRILL_DIR="${PULUMI_DRILL_DIR:-infra/pulumi-drill}"
EVIDENCE_DIR="${EVIDENCE_DIR:-/tmp/drill-evidence-${RUN_ID}}"
AUDIT_DOC_DIR="${AUDIT_DOC_DIR:-.claude/knowledge-base/audits}"

log() { printf '[drill-evidence-capture] %s\n' "$*" >&2; }

# --- Pre-flight ---
log "Pre-flight checks for run_id=$RUN_ID..."

if ! command -v git >/dev/null 2>&1; then
  log "ERROR: git not installed"
  exit 1
fi

mkdir -p "$EVIDENCE_DIR" || {
  log "ERROR: cannot create EVIDENCE_DIR: $EVIDENCE_DIR"
  exit 2
}

mkdir -p "$AUDIT_DOC_DIR" || {
  log "ERROR: cannot create AUDIT_DOC_DIR: $AUDIT_DOC_DIR"
  exit 2
}

AUDIT_DOC="$AUDIT_DOC_DIR/$(date -u +%Y-%m-%d)-drill-l-run-${RUN_ID}.md"

# --- Phase 1: Audit skeleton (write FIRST so it always exists) ---
log "Phase 1/4: Writing audit doc skeleton (always-run)..."

cat > "$AUDIT_DOC" <<EOF
---
type: audit
created_at: $(date -u +%Y-%m-%d)
updated_at: $(date -u +%Y-%m-%d)
updated_by: claude-drill-evidence-capture
run_id: $RUN_ID
status: in-progress
---

# Drill L-Run Evidence — $RUN_ID

> Generated by \`infra/scripts/drill-evidence-capture.sh\` (L2-unlock plan T4.7.bis).
> Per ADR D5: evidence persisted BEFORE pulumi destroy.

## Run identification

- **Run ID:** $RUN_ID
- **Started:** $(date -u +%Y-%m-%dT%H:%M:%SZ)
- **Evidence dir:** $EVIDENCE_DIR
- **Audit doc:** $AUDIT_DOC

## Capture steps

EOF

# --- Phase 2: Pulumi outputs (best-effort) ---
log "Phase 2/4: Capturing Pulumi stack outputs..."

PULUMI_OUT_FILE="$EVIDENCE_DIR/pulumi-outputs.json"
set +e
if command -v pulumi >/dev/null 2>&1 && [[ -d "$PULUMI_DRILL_DIR" ]]; then
  if [[ "$DRY_RUN" == "true" ]]; then
    echo "DRY-RUN: would capture pulumi outputs" > "$PULUMI_OUT_FILE"
    PULUMI_RC=0
  else
    (cd "$PULUMI_DRILL_DIR" && pulumi stack output --stack drill --json --show-secrets) > "$PULUMI_OUT_FILE" 2>&1
    PULUMI_RC=$?
  fi
else
  echo "tool-missing: pulumi or pulumi-drill dir not present" > "$PULUMI_OUT_FILE"
  PULUMI_RC=1
fi
set -e

if [[ "$PULUMI_RC" -eq 0 ]]; then
  log "  ✓ pulumi outputs captured to $PULUMI_OUT_FILE"
  {
    echo "### Pulumi outputs ✓"
    echo ""
    echo "- File: $PULUMI_OUT_FILE"
    echo ""
  } >> "$AUDIT_DOC"
else
  log "  ✗ pulumi outputs FAILED (exit $PULUMI_RC) — fragment preserved"
  {
    echo "### Pulumi outputs ✗ (exit $PULUMI_RC)"
    echo ""
    echo "Capture failed but error preserved in $PULUMI_OUT_FILE"
    echo ""
  } >> "$AUDIT_DOC"
fi

# --- Phase 3: kubectl pod manifests + metrics (best-effort per cluster) ---
log "Phase 3/4: Capturing kubectl evidence per cluster..."

for cluster in mgmt build runtime runtime-2; do
  KC="$DRILL_KUBECONFIG_DIR/$cluster.yaml"
  CLUSTER_OUT="$EVIDENCE_DIR/${cluster}-pods.yaml"
  set +e
  if [[ -r "$KC" ]] && command -v kubectl >/dev/null 2>&1; then
    if [[ "$DRY_RUN" == "true" ]]; then
      echo "DRY-RUN: would capture pods for $cluster" > "$CLUSTER_OUT"
      KC_RC=0
    else
      KUBECONFIG="$KC" kubectl get pods --all-namespaces -o yaml > "$CLUSTER_OUT" 2>&1
      KC_RC=$?
    fi
  else
    echo "skipped: kubeconfig not available for $cluster" > "$CLUSTER_OUT"
    KC_RC=1
  fi
  set -e

  if [[ "$KC_RC" -eq 0 ]]; then
    log "  ✓ $cluster pods captured to $CLUSTER_OUT"
    echo "- ✓ $cluster cluster pods ($CLUSTER_OUT)" >> "$AUDIT_DOC"
  else
    log "  ✗ $cluster pods capture FAILED — fragment preserved"
    echo "- ✗ $cluster cluster pods (exit $KC_RC, see $CLUSTER_OUT)" >> "$AUDIT_DOC"
  fi
done

# Capture loopruntime_* metrics from mgmt API
set +e
METRICS_OUT="$EVIDENCE_DIR/loopruntime-metrics.txt"
if [[ -r "$DRILL_KUBECONFIG_DIR/mgmt.yaml" ]] && command -v kubectl >/dev/null 2>&1; then
  if [[ "$DRY_RUN" == "true" ]]; then
    echo "DRY-RUN: would fetch metrics" > "$METRICS_OUT"
    M_RC=0
  else
    KUBECONFIG="$DRILL_KUBECONFIG_DIR/mgmt.yaml" \
      kubectl exec -n loopruntime-system deploy/loopruntime-api -- \
      wget -qO- http://localhost:9090/metrics 2>&1 | grep "^loopruntime_" > "$METRICS_OUT"
    M_RC=$?
  fi
else
  echo "skipped: mgmt kubeconfig unavailable" > "$METRICS_OUT"
  M_RC=1
fi
set -e

if [[ "$M_RC" -eq 0 ]]; then
  log "  ✓ loopruntime_* metrics captured to $METRICS_OUT"
  echo "- ✓ loopruntime_* metrics ($METRICS_OUT)" >> "$AUDIT_DOC"
else
  log "  ✗ metrics capture failed — partial fragment preserved"
  echo "- ✗ loopruntime_* metrics (exit $M_RC, see $METRICS_OUT)" >> "$AUDIT_DOC"
fi

# --- Phase 4: Commit local git (operator forensic recovery anchor) ---
log "Phase 4/4: Committing evidence locally (operator recovery anchor)..."

{
  echo ""
  echo "## Final status"
  echo ""
  echo "- Completed: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "- Evidence dir: $EVIDENCE_DIR"
  echo "- Audit doc: $AUDIT_DOC"
  echo ""
  echo "## Operator next steps"
  echo ""
  echo "1. Review evidence dir: \`ls $EVIDENCE_DIR\`"
  echo "2. Update this audit doc with L-level verdicts (PASS/FAIL/INCONCLUSIVE)"
  echo "3. Proceed with mandatory teardown: \`pulumi destroy --stack drill --yes --skip-preview\`"
  echo "4. Validate teardown clean: \`bash infra/scripts/drill-teardown-validator.sh\`"
} >> "$AUDIT_DOC"

if [[ "$DRY_RUN" == "true" ]]; then
  log "  DRY-RUN: skipping git commit"
  log "Audit doc skeleton: $AUDIT_DOC"
  log "Dry-run complete."
  exit 0
fi

# Local git commit (NOT pushed — local recovery only per ADR D5)
set +e
if git rev-parse --git-dir >/dev/null 2>&1; then
  git add "$AUDIT_DOC" 2>/dev/null
  if git diff --cached --quiet; then
    log "  No changes to commit (audit doc identical to previous)"
    GIT_RC=0
  else
    git commit -m "drill: partial evidence ${RUN_ID} (T4.7.bis pre-teardown)" --no-verify 2>>"$EVIDENCE_DIR/git-commit.log"
    GIT_RC=$?
  fi
else
  log "  not in git repo — skipping commit (evidence dir still preserved)"
  GIT_RC=0
fi
set -e

if [[ "$GIT_RC" -ne 0 ]]; then
  log "  ✗ git commit failed (see $EVIDENCE_DIR/git-commit.log)"
  log "    Evidence in $EVIDENCE_DIR is preserved on disk"
  exit 3
fi

log ""
log "✓ Evidence captured + committed locally."
log "  Audit doc: $AUDIT_DOC"
log "  Evidence files: $EVIDENCE_DIR"
log "  Next: review audit + perform mandatory teardown."
