/**
 * Stack references — typed, fail-fast, no invented values.
 *
 * Uses requireOutput() for all fields — if loopruntime-infra hasn't exported
 * the field, deployment fails immediately with a clear error.
 * No defaults, no fallbacks, no "from-ref" strings.
 */

import * as pulumi from "@pulumi/pulumi";

const cfg = new pulumi.Config();

// StackReference target is configurable per-stack for per-developer stacks.
// S3 backend requires format: organization/project/stack
// "organization" is a literal constant for DIY/S3 backends (not a real org name).
const infraStackName = cfg.get("infraStackRef") ?? `organization/loopruntime-infra/${pulumi.getStack()}`;

export const infraRef = new pulumi.StackReference(infraStackName);

// --- Typed accessors (fail-fast) ---

export const mgmtKubeconfig = infraRef.requireOutput("mgmtKubeconfig") as pulumi.Output<string>;
export const buildKubeconfig = infraRef.requireOutput("buildKubeconfig") as pulumi.Output<string>;
export const runtimeKubeconfig = infraRef.requireOutput("runtimeKubeconfig") as pulumi.Output<string>;

export const mgmtClusterEndpoint = infraRef.requireOutput("mgmtClusterEndpoint") as pulumi.Output<string>;
export const buildClusterEndpoint = infraRef.requireOutput("buildClusterEndpoint") as pulumi.Output<string>;
export const runtimeClusterEndpoint = infraRef.requireOutput("runtimeClusterEndpoint") as pulumi.Output<string>;

export const dbHost = infraRef.requireOutput("dbHost") as pulumi.Output<string>;
export const dbPort = infraRef.requireOutput("dbPort") as pulumi.Output<number>;
export const dbUri = infraRef.requireOutput("dbUri") as pulumi.Output<string>;
export const dbPassword = infraRef.requireOutput("dbPassword") as pulumi.Output<string>;

// Per-service DB credentials (role-separated users)
// NOT CONSUMED (measured 2026-09-07): dbGiteaUser and dbGiteaPassword are read
// from the infra stack and no module in pulumi-platform imports either. The
// producing side is real — infra/pulumi-infra/src/index.ts:208-209 exports both
// — so these accessors are a prepared seam, not a live wire.
export const dbGiteaUser = infraRef.requireOutput("dbGiteaUser") as pulumi.Output<string>;
export const dbGiteaPassword = infraRef.requireOutput("dbGiteaPassword") as pulumi.Output<string>;

export const registryEndpoint = infraRef.requireOutput("registryEndpoint") as pulumi.Output<string>;
export const registryName = infraRef.requireOutput("registryName") as pulumi.Output<string>;

export const spacesEndpoint = infraRef.requireOutput("spacesEndpoint") as pulumi.Output<string>;
export const s3Endpoint = infraRef.requireOutput("s3Endpoint") as pulumi.Output<string>;
export const logsBucketName = infraRef.requireOutput("logsBucketName") as pulumi.Output<string>;
export const staticBucketEndpoint = infraRef.requireOutput("staticBucketEndpoint") as pulumi.Output<string>;

// Docker credentials for K8s imagePullSecrets (generated by loopruntime-infra)
export const dockerConfigJson = infraRef.requireOutput("dockerConfigJson") as pulumi.Output<string>;
