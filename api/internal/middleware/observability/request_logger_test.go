// TestRequestLogger_BindsCorrelationIDIntoEnrichedLogger — the load-
// bearing integration: a request comes in with Correlation-ID header,
// CorrelationID middleware injects into ctx, RequestLogger enriches a
// logger and registers it, the handler retrieves and logs — the
// JSON output MUST contain correlation_id.
func TestRequestLogger_BindsCorrelationIDIntoEnrichedLogger(t *testing.T) {
	var buf bytes.Buffer
	base := slog.New(slog.NewJSONHandler(&buf, nil))
	cl := logging.NewContextLogger(base, nil)

	// Handler logs via LoggerFromContext — the canonical handler pattern.
	handler := func(w http.ResponseWriter, r *http.Request) {
		logger := logging.LoggerFromContext(r.Context())
		logger.Info("handler ran")
		w.WriteHeader(http.StatusOK)
	}

	// Wire: CorrelationID first, then RequestLogger, then the handler.
	stack := CorrelationID(RequestLogger(cl)(http.HandlerFunc(handler)))

	req := httptest.NewRequest(http.MethodGet, "/test", nil)
	req.Header.Set("Correlation-ID", "req-corr-probe")
	rec := httptest.NewRecorder()
	stack.ServeHTTP(rec, req)

	output := buf.String()
	if !strings.Contains(output, `"correlation_id":"req-corr-probe"`) {
		t.Errorf("expected log JSON to contain correlation_id=req-corr-probe, got: %s", output)
	}
}

// TestRequestLogger_NilContextLoggerIsNoOp — defensive nil safety.
// Some test setups wire CorrelationID without setting up the
// ContextLogger; the request must still succeed (handler falls back
// to slog.Default).
func TestRequestLogger_NilContextLoggerIsNoOp(t *testing.T) {
	called := false
	handler := func(w http.ResponseWriter, r *http.Request) {
		_ = logging.LoggerFromContext(r.Context()) // would panic if nil
		called = true
		w.WriteHeader(http.StatusOK)
	}

	stack := CorrelationID(RequestLogger(nil)(http.HandlerFunc(handler)))
	req := httptest.NewRequest(http.MethodGet, "/test", nil)
	rec := httptest.NewRecorder()
	stack.ServeHTTP(rec, req)

	if !called {
		t.Fatal("handler must run even when ContextLogger is nil")
	}
	if rec.Code != http.StatusOK {
		t.Errorf("expected 200, got %d", rec.Code)
	}
}

// TestRequestLogger_GeneratedCorrelationIDInjected — when the client
// does NOT supply Correlation-ID, the CorrelationID middleware
// generates a UUID; the enriched logger must carry that generated
// value, not be empty.
func TestRequestLogger_GeneratedCorrelationIDInjected(t *testing.T) {
	var buf bytes.Buffer
	base := slog.New(slog.NewJSONHandler(&buf, nil))
	cl := logging.NewContextLogger(base, nil)

	handler := func(w http.ResponseWriter, r *http.Request) {
		logging.LoggerFromContext(r.Context()).Info("generated-id-test")
		w.WriteHeader(http.StatusOK)
	}

	stack := CorrelationID(RequestLogger(cl)(http.HandlerFunc(handler)))
	req := httptest.NewRequest(http.MethodGet, "/test", nil)
	// NO Correlation-ID header — middleware should generate
	rec := httptest.NewRecorder()
	stack.ServeHTTP(rec, req)

	// Parse the JSON and confirm correlation_id is a non-empty UUID-shaped value.
	type logEntry struct {
		CorrelationID string `json:"correlation_id"`
		Msg           string `json:"msg"`
	}
	var entry logEntry
	dec := json.NewDecoder(&buf)
	if err := dec.Decode(&entry); err != nil {
		t.Fatalf("could not parse log JSON: %v", err)
	}
	if entry.CorrelationID == "" {
		t.Error("correlation_id must be non-empty (generated by CorrelationID middleware)")
	}
	if len(entry.CorrelationID) < 16 {
		t.Errorf("correlation_id too short to be UUID v4: %q", entry.CorrelationID)
	}

	// And the response header should also echo it (smoke check of CorrelationID middleware).
	if rec.Header().Get("Correlation-ID") == "" {
		t.Error("response Correlation-ID header missing")
	}
}

// TestRequestLogger_AcceptsPreSetCorrelation — when correlation is
// added to ctx before this middleware (e.g. by a custom middleware),
// RequestLogger picks it up via the canonical correlation pkg.
func TestRequestLogger_AcceptsPreSetCorrelation(t *testing.T) {
	var buf bytes.Buffer
	base := slog.New(slog.NewJSONHandler(&buf, nil))
	cl := logging.NewContextLogger(base, nil)

	handler := func(w http.ResponseWriter, r *http.Request) {
		logging.LoggerFromContext(r.Context()).Info("preset")
		w.WriteHeader(http.StatusOK)
	}

	// Skip CorrelationID middleware; inject directly into ctx.
	innerStack := RequestLogger(cl)(http.HandlerFunc(handler))

	req := httptest.NewRequest(http.MethodGet, "/test", nil)
	ctx := correlation.WithID(req.Context(), "preset-id")
	req = req.WithContext(ctx)
	rec := httptest.NewRecorder()
	innerStack.ServeHTTP(rec, req)

	if !strings.Contains(buf.String(), `"correlation_id":"preset-id"`) {
		t.Errorf("expected preset-id in log output: %s", buf.String())
	}
}
