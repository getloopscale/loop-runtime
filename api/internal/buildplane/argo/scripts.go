// scripts.go contains all shell script generation functions used by language strategies.
// Each function returns a shell script string that runs inside a build container.
//
// All user-supplied paths (from loopzero.yaml) are escaped via shellgen.ShellQuote
// to prevent shell injection. Complex shell constructs use Raw() where they
// don't involve user input.

import (
	"fmt"

	"github.com/getloopscale/loopzero/api/internal/deploycontracts"

	"github.com/getloopscale/loopzero/api/internal/buildplane/shellgen"
)

// ---------------------------------------------------------------------------
// Node.js scripts
// ---------------------------------------------------------------------------

func scriptValidateNode(apps []deploycontracts.AppSpec) string {
	paths := appPaths(apps)
	b := shellgen.New().SetE().Cd("/workspace").
		Echo("Validating workspace...").
		Raw(`ERRORS=""`)

	// Check package.json exists at each app path
	appendValidateFile(b, paths, "package.json")

	// Check lockfile at root OR at any app path
	b.Raw(`LOCKFILES="package-lock.json yarn.lock pnpm-lock.yaml"`)
	b.Raw(`HAS_LOCK=false`)
	b.Raw(`for f in $LOCKFILES; do`)
	b.Raw(`  [ -f "$f" ] && HAS_LOCK=true`)
	b.Raw(`done`)

	for _, p := range paths {
		b.Raw(`for f in $LOCKFILES; do`)
		b.Raw(fmt.Sprintf(`  [ -f %s"/$f" ] && HAS_LOCK=true`, shellgen.ShellQuote(p)))
		b.Raw(`done`)
	}

	// Lockfile check: warn if missing, don't block. The Dockerfile or install step
	// handles the actual failure with a clear message. Model: Vercel/Railway behavior —
	// lockfile absence is the user's responsibility, not a platform gate.
	// If npm ci is in their Dockerfile, Docker itself fails clearly.
	// If no Dockerfile, scriptInstallNode falls back to npm install with a warning.
	b.Raw(`if [ "$HAS_LOCK" = "false" ]; then`)
	b.Raw(`  echo "WARNING: No lockfile found. Builds may be non-deterministic. Consider running npm install and committing the lockfile."`)
	b.Raw(`fi`)

	appendErrorExit(b)
	b.Echo("Workspace validation passed")
	return b.String() + "\n"
}

// scriptInstallNode generates the install-deps step shell script.
//
// CHG-002b 2026-04-28 — workspace-aware install. When the project root has
// turbo.json / pnpm-workspace.yaml / package.json#workspaces, install runs
// ONCE at the root with the chosen package manager, so:
//   - npm/pnpm/yarn workspace hoisting works
//   - cross-package symlinks are created
//   - subsequent build steps (or BuildKit Dockerfile generated by loopzero-packs)
//     can compile cross-workspace TypeScript imports
//
// For standalone projects, falls back to the per-app behavior so single-app
// fixtures (hello-server, multi-app's individual entries) keep working.
func scriptInstallNode(apps []deploycontracts.AppSpec) string {
	paths := appPaths(apps)
	b := shellgen.New().SetE().Cd("/workspace")

	// Detect workspace at runtime (script-level): if root has any of these
	// markers, install at root. We can't reach loopzero-packs detection here
	// because this script runs inside the build container, not the API.
	b.Raw(`# CHG-002b: workspace-aware install — root if monorepo, else per-app.`)
	b.Raw(`if [ -f /workspace/turbo.json ] || [ -f /workspace/pnpm-workspace.yaml ] || (grep -q '"workspaces"' /workspace/package.json 2>/dev/null); then`)
	b.Raw(`  echo "Detected Node workspace monorepo — installing at /workspace root"`)
	b.Raw(`  cd /workspace`)
	b.Raw(`  if [ -f pnpm-lock.yaml ]; then`)
	b.Raw(`    corepack enable && pnpm install --frozen-lockfile`)
	b.Raw(`  elif [ -f yarn.lock ]; then`)
	b.Raw(`    corepack enable && yarn install --frozen-lockfile`)
	b.Raw(`  elif [ -f package-lock.json ]; then`)
	b.Raw(`    npm ci`)
	b.Raw(`  else`)
	b.Raw(`    echo "WARNING: No lockfile at workspace root — running npm install"`)
	b.Raw(`    npm install`)
	b.Raw(`  fi`)
	b.Raw(`  echo "Workspace dependencies installed"`)
	b.Raw(`else`)
	b.Raw(`  echo "Standalone project — installing per app"`)
	for _, p := range paths {
		dir := "/workspace/" + p
		b.Raw(fmt.Sprintf(`  echo "Installing deps in %s..."`, shellgen.ShellQuote(p)))
		b.Raw(fmt.Sprintf(`  cd %s`, shellgen.ShellQuote(dir)))
		b.Raw(`  if [ -f pnpm-lock.yaml ]; then`)
		b.Raw(`    corepack enable && pnpm install --frozen-lockfile`)
		b.Raw(`  elif [ -f yarn.lock ]; then`)
		b.Raw(`    corepack enable && yarn install --frozen-lockfile`)
		b.Raw(`  elif [ -f package-lock.json ]; then`)
		b.Raw(`    npm ci`)
		b.Raw(`  else`)
		b.Raw(fmt.Sprintf(`    echo "WARNING: No lockfile in %s — running npm install"`, shellgen.ShellQuote(p)))
		b.Raw(`    npm install`)
		b.Raw(`  fi`)
		b.Raw(fmt.Sprintf(`  echo "Dependencies installed in %s"`, shellgen.ShellQuote(p)))
	}
	b.Raw(`fi`)
	return b.String() + "\n"
}

// scriptBuildNode generates the build-apps step shell script.
//
// CHG-002b 2026-04-28 — workspace-aware build. In monorepos with turbo /
// pnpm-workspaces / npm-workspaces, runs the build at the root with proper
// filtering:
//   - turbo.json present: `npx turbo run build` (builds full graph in topo order)
//   - pnpm-workspaces:    `pnpm -r run build` (recursive, topo order)
//   - npm/yarn workspaces: `<pm> run build --workspaces --if-present`
//
// We don't restrict the build to a single app here because LoopZero's
// build-apps DAG step happens BEFORE per-app Docker images are built;
// building the full workspace graph guarantees every app's deps are
// compiled before BuildKit picks up the image stage. The per-app
// Dockerfile generated by loopzero-packs may filter further.
//
// For standalone projects, falls back to the per-app behavior.
func scriptBuildNode(apps []deploycontracts.AppSpec) string {
	paths := appPaths(apps)
	b := shellgen.New().SetE().Cd("/workspace")
	b.Raw(`# CHG-002b: workspace-aware build — full graph if monorepo, else per-app.`)
	b.Raw(`if [ -f /workspace/turbo.json ]; then`)
	b.Raw(`  echo "Workspace with turbo detected — running 'npx turbo run build'"`)
	b.Raw(`  cd /workspace && npx turbo run build`)
	b.Raw(`elif [ -f /workspace/pnpm-workspace.yaml ]; then`)
	b.Raw(`  echo "pnpm workspace detected — running 'pnpm -r run build --if-present'"`)
	b.Raw(`  cd /workspace && corepack enable && pnpm -r run build --if-present`)
	b.Raw(`elif grep -q '"workspaces"' /workspace/package.json 2>/dev/null; then`)
	b.Raw(`  echo "npm/yarn workspace detected — running '<pm> run build --workspaces --if-present'"`)
	b.Raw(`  cd /workspace`)
	b.Raw(`  if [ -f yarn.lock ]; then`)
	b.Raw(`    yarn run build --workspaces --if-present`)
	b.Raw(`  else`)
	b.Raw(`    npm run build --workspaces --if-present`)
	b.Raw(`  fi`)
	b.Raw(`else`)
	b.Raw(`  echo "Standalone project — building per app"`)
	for _, p := range paths {
		dir := "/workspace/" + p
		b.Raw(fmt.Sprintf(`  echo "Building %s..."`, shellgen.ShellQuote(p)))
		b.Raw(fmt.Sprintf(`  cd %s && npm run build --if-present`, shellgen.ShellQuote(dir)))
		b.Raw(fmt.Sprintf(`  echo "Build completed for %s"`, shellgen.ShellQuote(p)))
	}
	b.Raw(`fi`)
	return b.String() + "\n"
}

func scriptScanNode() string {
	b := shellgen.New().Raw("set -uo pipefail").Cd("/workspace")
	b.Raw(`if [ -f package-lock.json ]; then`).
		Raw(`  npm audit --audit-level=critical 2>&1 || {`).
		Raw(`    echo "ERROR: npm audit found critical vulnerabilities"`).
		Raw(`    exit 1`).
		Raw(`  }`).
		Raw(`else`).
		Raw(`  echo "No package-lock.json found — skipping npm audit"`).
		Raw(`fi`)
	return b.String() + "\n"
}

