// Package integration tests database hardening (MEET-2026-03-31-024 Phase 1).
//
// These tests verify:
// 1. Role separation: loopruntime_api cannot execute DDL
// 2. RLS is enabled AND forced on every tenant-scoped table
// 3. CHECK constraints and indexes from the hardening migration exist
// 4. audit_log is append-only
// 5. Reconciliation reaches every tenant as loopruntime_worker, via the named policy
//
// Item 3 used to read "RLS bypass: system queries (no tenant_id set) see all
// rows". That was the exposure, not a feature: migration 000062 made the
// policies fail-closed, and cross-tenant work now goes through an explicit
// policy granted to loopruntime_worker instead of an unset session variable.
//
// Tenant-isolation behaviour itself is covered in tenant_isolation_rls_audit_test.go,
// which runs over the request-path role rather than the owner.
//
// These tests require a real PostgreSQL instance with the schema and migration
// 000062 applied. They skip when DATABASE_URL is unreachable — set
// LOOPRUNTIME_RLS_AUDIT_REQUIRE=1 in CI so a missing database fails instead.
package integration

import (
	"context"
	"errors"
	"fmt"
	"os"
	"testing"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// setupHardeningTestDB creates a pool and ensures migrations are applied.
func setupHardeningTestDB(t *testing.T) *pgxpool.Pool {
	t.Helper()

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	pool, err := pgxpool.New(ctx, dbURL())
	if err != nil {
		t.Skipf("skipping: cannot connect to PostgreSQL: %v", err)
	}

	// Check if migration 000009 has been applied by checking for RLS
	var rlsEnabled bool
	err = pool.QueryRow(ctx,
		"SELECT relrowsecurity FROM pg_class WHERE relname = 'builds'").Scan(&rlsEnabled)
	if err != nil || !rlsEnabled {
		t.Skipf("skipping: migration 000009 not applied (RLS not enabled on builds)")
	}

	t.Cleanup(func() { pool.Close() })
	return pool
}

// TestRLSTenantIsolation was removed by migration 000062's companion change.
//
// It connected through dbURL() — the OWNER role — and asserted isolation over a
// connection that structurally cannot be isolated: an owner bypasses its own
// policies, and (before 000062) FORCE was off. It also never executed, because
// ci.yml had no `services:` block, so it skipped on an unreachable database and
// reported green for five months over a control nobody had measured.
//
// Its coverage now lives in tenant_isolation_rls_audit_test.go, which runs over
// LOOPRUNTIME_API_DATABASE_URL (the real request-path role), refuses to run at all on a
// role that can bypass RLS, and additionally covers the write direction and the
// worker's cross-tenant reach:
//
//	TestTenantIsolation_ScopedRead_SeesOnlyOwnTenant
//	TestTenantIsolation_MissingContext_SeesNothing
//	TestTenantIsolation_CannotWriteForAnotherTenant
//	TestTenantIsolation_WorkerRole_KeepsCrossTenantReach

// TestRLSOnAllTenantTables verifies RLS is active on every tenant-scoped table.
func TestRLSOnAllTenantTables(t *testing.T) {
	pool := setupHardeningTestDB(t)
	ctx := context.Background()

	tenantTables := []string{
		"builds", "releases", "environment_targets", "secrets",
		"projects", "tenant_members", "audit_log", "idempotency_keys",
	}

	for _, table := range tenantTables {
		t.Run(fmt.Sprintf("RLS enabled on %s", table), func(t *testing.T) {
			var rlsEnabled, rlsForced bool
			err := pool.QueryRow(ctx,
				"SELECT relrowsecurity, relforcerowsecurity FROM pg_class WHERE relname = $1",
				table).Scan(&rlsEnabled, &rlsForced)
			if err != nil {
				t.Fatalf("query pg_class for %s: %v", table, err)
			}
			if !rlsEnabled {
				t.Errorf("RLS not enabled on %s", table)
			}
			if !rlsForced {
				t.Errorf("RLS not forced on %s (table owner bypasses)", table)
			}
		})
	}
}

// TestCheckConstraintsOnStatus verifies CHECK constraints exist on status columns.
func TestCheckConstraintsOnStatus(t *testing.T) {
	pool := setupHardeningTestDB(t)
	ctx := context.Background()

	// T0.4 (deep-review-remediation): the original test queried 'chk_builds_status'
	// and 'chk_releases_status' which do not exist. The actual constraint names
	// (auto-generated by PostgreSQL from CREATE TABLE ... CHECK (status IN (...)))
	// are 'builds_status_check' and 'releases_status_check'. The wrong names made
	// the test fail-open (zero rows matched, EXISTS returned false, but the
	// assertion was for non-existence — actually the test was checking the wrong
	// thing). This was the broken canary that masked find_data_001 from CI.
	t.Run("builds status CHECK constraint exists", func(t *testing.T) {
		var exists bool
		err := pool.QueryRow(ctx,
			"SELECT EXISTS(SELECT 1 FROM pg_constraint WHERE conname = 'builds_status_check')").Scan(&exists)
		if err != nil {
			t.Fatalf("query: %v", err)
		}
		if !exists {
			t.Error("CHECK constraint builds_status_check does not exist (canary: test would fail-open if name were wrong)")
		}
	})

	t.Run("releases status CHECK constraint exists", func(t *testing.T) {
		var exists bool
		err := pool.QueryRow(ctx,
			"SELECT EXISTS(SELECT 1 FROM pg_constraint WHERE conname = 'releases_status_check')").Scan(&exists)
		if err != nil {
			t.Fatalf("query: %v", err)
		}
		if !exists {
			t.Error("CHECK constraint releases_status_check does not exist (canary: test would fail-open if name were wrong)")
		}
	})

	t.Run("invalid build status rejected by CHECK", func(t *testing.T) {
		_, err := pool.Exec(ctx,
			`INSERT INTO builds (id, tenant_id, project_id, environment, status, correlation_id, created_by)
			 VALUES ('bld-invalid-status', 'test', 'proj', 'prod', 'INVALID_STATUS', 'corr', 'test')`)
		if err == nil {
			// Cleanup if somehow it succeeded
			_, _ = pool.Exec(ctx, "DELETE FROM builds WHERE id = 'bld-invalid-status'")
			t.Error("expected CHECK constraint violation for invalid status, but INSERT succeeded")
		}
	})
}

// TestRolesExist verifies that the roles the platform connects as exist, and
// that none of them can escape Row Level Security.
//
// The inventory is the one the code and the migrations use: loopruntime_api (the
// request path), loopruntime_worker (the background loops, migration 000023) and
// loopruntime_cloud (the control plane, migration 000063). It used to name
// loopruntime_migrate and loopruntime_readonly, which no migration, chart or connection in
// this repository creates or uses — the test-roles fixture created them only so
// this test would pass, and a database built by the migrations failed it
// (issue #387).
func TestRolesExist(t *testing.T) {
	pool := setupHardeningTestDB(t)
	ctx := context.Background()

	roles := []string{"loopruntime_api", "loopruntime_worker", "loopruntime_cloud"}
	for _, role := range roles {
		t.Run(fmt.Sprintf("role %s exists and is bound by RLS", role), func(t *testing.T) {
			var super, bypass bool
			err := pool.QueryRow(ctx,
				"SELECT rolsuper, rolbypassrls FROM pg_roles WHERE rolname = $1", role).Scan(&super, &bypass)
			if errors.Is(err, pgx.ErrNoRows) {
				t.Fatalf("role %s does not exist", role)
			}
			if err != nil {
				t.Fatalf("query: %v", err)
			}
			if super || bypass {
				t.Errorf("role %s escapes Row Level Security (rolsuper=%v rolbypassrls=%v)", role, super, bypass)
			}
		})
	}
}

// TestLoopRuntimeApiCannotDDL verifies the loopruntime_api role cannot execute DDL operations.
// This test requires connecting as loopruntime_api via LOOPRUNTIME_API_DATABASE_URL env var.
// Skips if the env var is not set or connection fails.
func TestLoopRuntimeApiCannotDDL(t *testing.T) {
	ctx := context.Background()

	// Use a dedicated env var for the loopruntime_api connection string.
	// This avoids overwriting with the admin URL from DATABASE_URL.
	apiURL := os.Getenv("LOOPRUNTIME_API_DATABASE_URL")
	if apiURL == "" {
		t.Skip("skipping: LOOPRUNTIME_API_DATABASE_URL not set (needed to test loopruntime_api role)")
	}

	connCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()

	pool, err := pgxpool.New(connCtx, apiURL)
	if err != nil {
		t.Skipf("skipping: cannot connect as loopruntime_api: %v", err)
	}
	defer pool.Close()

	t.Run("DROP TABLE is denied", func(t *testing.T) {
		_, err := pool.Exec(ctx, "DROP TABLE IF EXISTS builds")
		if err == nil {
			t.Error("expected permission denied for DROP TABLE, but it succeeded!")
		}
	})

	t.Run("ALTER TABLE is denied", func(t *testing.T) {
		_, err := pool.Exec(ctx, "ALTER TABLE builds ADD COLUMN test_col TEXT")
		if err == nil {
			_, _ = pool.Exec(ctx, "ALTER TABLE builds DROP COLUMN test_col")
			t.Error("expected permission denied for ALTER TABLE, but it succeeded!")
		}
	})

	t.Run("TRUNCATE is denied", func(t *testing.T) {
		_, err := pool.Exec(ctx, "TRUNCATE builds")
		if err == nil {
			t.Error("expected permission denied for TRUNCATE, but it succeeded!")
		}
	})

	t.Run("SELECT is allowed", func(t *testing.T) {
		_, err := pool.Exec(ctx, "SELECT 1 FROM builds LIMIT 1")
		if err != nil {
			t.Errorf("expected SELECT to be allowed, got: %v", err)
		}
	})
}

// TestAuditLogAppendOnly verifies the audit_log table rejects UPDATE and DELETE.
func TestAuditLogAppendOnly(t *testing.T) {
	pool := setupHardeningTestDB(t)
	ctx := context.Background()

	// The fixture writes the way production writes: INSIDE the tenant context.
	//
	// Before 000064 this row got in because the owner carried the
	// audit_log_owner_maintenance policy (USING true) — the bypass that migration
	// removed. Without a context, fail-closed RLS rejects the INSERT, and that is
	// what must happen: the test is about the append-only trigger, and seeding the
	// fixture outside the barrier tested the trigger on a path production does not have.
	if _, err := pool.Exec(ctx, `SELECT set_config('app.tenant_id', 'test-audit', false)`); err != nil {
		t.Fatalf("set tenant context: %v", err)
	}
	_, err := pool.Exec(ctx,
		`INSERT INTO audit_log (tenant_id, action, actor, resource_type, resource_id, correlation_id)
		 VALUES ('test-audit', 'TEST', 'test', 'test', 'test-id', 'corr-test')`)
	if err != nil {
		t.Fatalf("failed to insert audit entry: %v", err)
	}

	t.Run("UPDATE on audit_log is rejected by trigger", func(t *testing.T) {
		// The deferred trigger fires at commit — we need to commit to see the error
		tx, err := pool.BeginTx(ctx, pgx.TxOptions{})
		if err != nil {
			t.Fatalf("begin tx: %v", err)
		}

		_, err = tx.Exec(ctx,
			"UPDATE audit_log SET action = 'TAMPERED' WHERE tenant_id = 'test-audit'")
		if err != nil {
			// Some configurations reject immediately
			_ = tx.Rollback(ctx)
			return // Expected — trigger fired
		}

		// Deferred trigger fires at commit
		err = tx.Commit(ctx)
		if err == nil {
			t.Error("expected audit_log UPDATE to be rejected by trigger, but commit succeeded")
		}
	})

	t.Run("DELETE on audit_log is rejected by trigger", func(t *testing.T) {
		tx, err := pool.BeginTx(ctx, pgx.TxOptions{})
		if err != nil {
			t.Fatalf("begin tx: %v", err)
		}

		_, err = tx.Exec(ctx,
			"DELETE FROM audit_log WHERE tenant_id = 'test-audit'")
		if err != nil {
			_ = tx.Rollback(ctx)
			return // Expected — trigger fired
		}

		err = tx.Commit(ctx)
		if err == nil {
			t.Error("expected audit_log DELETE to be rejected by trigger, but commit succeeded")
		}
	})

	// Cleanup — need to disable trigger temporarily to clean test data
	// In production, old audit entries would be archived via partition rotation
	t.Cleanup(func() {
		_, _ = pool.Exec(ctx, "ALTER TABLE audit_log DISABLE TRIGGER trg_audit_log_immutable")
		_, _ = pool.Exec(ctx, "DELETE FROM audit_log WHERE tenant_id = 'test-audit'")
		_, _ = pool.Exec(ctx, "ALTER TABLE audit_log ENABLE TRIGGER trg_audit_log_immutable")
	})
}

// TestReconciliationQueriesWithRLS verifies that cross-tenant system queries
// (FindActiveBuilds, FindPendingReleases patterns) work with RLS active.
func TestReconciliationQueriesWithRLS(t *testing.T) {
	ctx, pool := auditPool(t, "DATABASE_URL", "owner")

	// Reuses the shared fixture: builds carries a trigger that resolves cell_id
	// from the tenant, so the row needs the real user → account → cell → tenant
	// chain behind it. The previous inline seed inserted an orphan build and had
	// been broken since migration 000061 added that trigger — invisible, because
	// this test had never run against a database.
	tenantA, tenantB, buildA, buildB := seedTwoTenants(t, ctx, pool)

	// The reconciliation loop legitimately scans every tenant. Since migration
	// 000062 it earns that reach through a named policy on loopruntime_worker, not by
	// leaving the context unset and falling through a permissive disjunct.
	//
	// The distinction matters operationally: a named grant is visible in
	// pg_policy and shows up in an audit; an empty string that happens to
	// disable the predicate looks like ordinary application code.
	t.Run("FindActiveBuilds pattern reaches both tenants as loopruntime_worker", func(t *testing.T) {
		wctx, worker := auditPool(t, "LOOPRUNTIME_WORKER_DATABASE_URL", "worker (loopruntime_worker)")

		rows, err := worker.Query(wctx,
			`SELECT id, tenant_id FROM builds
			 WHERE status IN ('QUEUED', 'RUNNING')
			 AND id IN ($1, $2)`,
			buildA, buildB)
		if err != nil {
			t.Fatalf("query: %v", err)
		}
		defer rows.Close()

		seen := map[string]bool{}
		for rows.Next() {
			var id, tid string
			if err := rows.Scan(&id, &tid); err != nil {
				t.Fatalf("scan: %v", err)
			}
			seen[tid] = true
		}

		if !seen[tenantA] || !seen[tenantB] {
			t.Errorf("reconciliation must reach both tenants as loopruntime_worker, saw: %v.\n"+
				"Check the *_worker_cross_tenant policies from migration 000062.", seen)
		}
	})
}

// TestIndexesExist verifies that migration 000009 indexes were created.
func TestIndexesExist(t *testing.T) {
	pool := setupHardeningTestDB(t)
	ctx := context.Background()

	indexes := []string{
		"idx_releases_build_id",
		"idx_releases_pending",
	}

	for _, idx := range indexes {
		t.Run(fmt.Sprintf("index %s exists", idx), func(t *testing.T) {
			var exists bool
			err := pool.QueryRow(ctx,
				"SELECT EXISTS(SELECT 1 FROM pg_indexes WHERE indexname = $1)", idx).Scan(&exists)
			if err != nil {
				t.Fatalf("query: %v", err)
			}
			if !exists {
				t.Errorf("index %s does not exist", idx)
			}
		})
	}

	t.Run("redundant idempotency index was dropped", func(t *testing.T) {
		var exists bool
		err := pool.QueryRow(ctx,
			"SELECT EXISTS(SELECT 1 FROM pg_indexes WHERE indexname = 'idempotency_keys_key_tenant_idx')").Scan(&exists)
		if err != nil {
			t.Fatalf("query: %v", err)
		}
		if exists {
			t.Error("redundant index idempotency_keys_key_tenant_idx should have been dropped")
		}
	})
}
